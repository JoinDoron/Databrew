export const DEPARTMENTS = SOLUTIONS.filter(solution => solution.kind === "department");
export const INDUSTRIES = SOLUTIONS.filter(solution => solution.kind === "industry");
export const solutionHref = (solution: Pick<Solution, "slug">) => `/solutions/${solution.slug}`;
export const findSolution = (slug: string) => SOLUTIONS.find(solution => solution.slug === slug);

/** Keep subgroup context in filtered navigation without making a second entry. */
export function solutionGroups(kind: SolutionKind, query = "") {
    const entries = kind === "department" ? DEPARTMENTS : INDUSTRIES;
    const term = query.trim().toLowerCase();
    const matches = (item: Solution) => `${item.name} ${item.summary} ${item.slug}`.toLowerCase().includes(term);
    return entries.filter(item => !item.parent).map(parent => ({
        parent,
        children: entries.filter(child => child.parent === parent.slug && (matches(parent) || matches(child))),
    })).filter(group => matches(group.parent) || group.children.length > 0);
}
